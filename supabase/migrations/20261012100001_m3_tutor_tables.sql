-- 22 M3 tutor, part 1: the four tables (docs/m3-plan.md "The server surface", ADR 0008).
--
--   tutor_sessions     one row per lesson conversation of a child (unit, version, counters, the turn in flight)
--   tutor_messages     the messages of a session: REDACTED text only (the raw text of a child exists in memory in the
--                      edge function and nowhere else). Two rows per turn (child, tutor) that share client_turn_id.
--   tutor_daily_usage  turns per child per day (the daily budget; an atomic counter)
--   safeguarding_cases the human review queue of the safeguarding protocol (docs/safeguarding-protocol.md): a case holds
--                      a redacted excerpt and is read only by the `safeguarding` and `super_admin` roles
--
-- ACCESS. RLS is on for all four and NOTHING is granted to any API role (service_role included), and there is no
-- policy: reads and writes go through SECURITY DEFINER RPCs only (migrations m3_tutor_rpcs, m3_safeguarding_rpcs).
-- A guardian therefore cannot read a message by any path that does not first check the elevation and the withholding
-- rules, and a flagged turn is never reachable by a plain select. Child-data rows carry household_id and child_id; the
-- composite foreign key to children (id, household_id) makes them unable to disagree.
--
-- NO RAW TEXT ANYWHERE. `tutor_messages.text` and the case `excerpt` hold what remains after redaction. No table of this
-- file has a column for the original text, an audio clip or a transcript of the unredacted message (pgTAP 090 lists the
-- columns). `ai_usage` rows of tutor calls carry tokens only.
--
-- NO sync_seq: tutor data is never synced to devices.
--
-- The one extra column of ai_usage: `tutor_session_id` (a tutor call has no job; job_id was already nullable).

-- tutor_sessions ------------------------------------------------------------------------------------------------------
create table public.tutor_sessions (
  id uuid primary key default gen_random_uuid(),
  household_id uuid not null,
  child_id uuid not null,
  unit_id uuid not null references public.units (id),
  -- the pack version the conversation was grounded in when it opened
  version_no int not null check (version_no >= 1),
  model text check (model is null or char_length(model) <= 100),
  prompt_version text check (prompt_version is null or char_length(prompt_version) <= 64),
  started_at timestamptz not null default now(),
  last_active_at timestamptz not null default now(),
  -- stored turns (a failed turn is stored too)
  turn_count int not null default 0 check (turn_count >= 0),
  -- some turn of the session opened a safeguarding case: its messages follow the case in the purge
  flagged boolean not null default false,
  -- ONE turn in flight per session: the claim of the running turn and the time it expires (a killed worker leaves an
  -- expired claim that the next turn may take over)
  in_flight_turn_id uuid,
  in_flight_until timestamptz,
  constraint tutor_sessions_in_flight_chk check ((in_flight_turn_id is null) = (in_flight_until is null)),
  constraint tutor_sessions_child_household_fk foreign key (child_id, household_id)
    references public.children (id, household_id) on delete cascade,
  -- target of the composite FK that keeps tutor_messages.child_id consistent with its session
  constraint tutor_sessions_id_child_key unique (id, child_id)
);
create index tutor_sessions_child_household_idx on public.tutor_sessions (child_id, household_id);
create index tutor_sessions_child_started_idx on public.tutor_sessions (child_id, started_at desc);
create index tutor_sessions_unit_id_idx on public.tutor_sessions (unit_id);
-- a turn id claims at most one session of the child (finds the session of a retried first turn)
create unique index tutor_sessions_in_flight_turn_uidx on public.tutor_sessions (child_id, in_flight_turn_id)
  where in_flight_turn_id is not null;

comment on table public.tutor_sessions is
  'Tutor conversations. No client privilege and no policy: read through list_tutor_sessions (guardian + elevation), written by the service-role tutor_* RPCs.';

-- tutor_messages ------------------------------------------------------------------------------------------------------
create table public.tutor_messages (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null,
  household_id uuid not null,
  child_id uuid not null,
  -- generated by the client; both messages of a turn carry it, so a retry finds the stored turn
  client_turn_id uuid not null,
  -- position in the session (child 2n-1, tutor 2n); survives the purge of older messages
  seq int not null check (seq >= 1),
  role text not null check (role in ('child', 'tutor')),
  -- how the child gave the message (child rows only)
  input_mode text check (input_mode in ('text', 'voice')),
  -- REDACTED text only. NULL only for the reply of a failed turn.
  text text check (text is null or char_length(text) <= 4000),
  redaction_count int not null default 0 check (redaction_count >= 0),
  status text not null check (status in ('complete', 'replaced', 'blocked', 'safe_reply', 'failed')),
  -- the SafetyDecision of the turn (tutor row): action, reply key, the categories that drove it
  safety jsonb check (safety is null or jsonb_typeof(safety) = 'object'),
  -- advisory only (CLAUDE.md rule 4): never a progress event
  evidence jsonb not null default '[]'::jsonb check (jsonb_typeof(evidence) = 'array'),
  show_activity jsonb check (show_activity is null or jsonb_typeof(show_activity) = 'object'),
  -- the turn opened a case (or was marked to be withheld): purge and guardian visibility follow the case
  flagged boolean not null default false,
  -- the safety decision asked to withhold the turn from the guardian until a reviewer decides
  withheld boolean not null default false,
  -- the category that drove the flag (decides whether guardian_visible_categories applies)
  flag_category text check (
    flag_category is null or flag_category in
      ('self_harm', 'abuse_disclosure', 'distress', 'sexual', 'violence', 'personal_info_shared', 'jailbreak', 'off_topic')
  ),
  created_at timestamptz not null default now(),
  constraint tutor_messages_input_mode_chk check ((role = 'child') = (input_mode is not null)),
  constraint tutor_messages_text_chk check (text is not null or (role = 'tutor' and status = 'failed')),
  constraint tutor_messages_session_fk foreign key (session_id, child_id)
    references public.tutor_sessions (id, child_id) on delete cascade,
  constraint tutor_messages_child_household_fk foreign key (child_id, household_id)
    references public.children (id, household_id) on delete cascade,
  -- client_turn_id is unique per child (and role: a turn has one child message and one tutor message)
  constraint tutor_messages_turn_key unique (child_id, client_turn_id, role),
  constraint tutor_messages_session_seq_key unique (session_id, seq)
);
create index tutor_messages_child_household_idx on public.tutor_messages (child_id, household_id);
create index tutor_messages_child_created_idx on public.tutor_messages (child_id, created_at);
create index tutor_messages_session_child_idx on public.tutor_messages (session_id, child_id);
-- the purge scans by age
create index tutor_messages_created_idx on public.tutor_messages (created_at);

comment on table public.tutor_messages is
  'REDACTED tutor messages (two rows per turn). No client privilege and no policy: read through get_tutor_transcript (guardian + elevation; flagged turns are withheld until a reviewer releases them), written by tutor_save_turn.';
comment on column public.tutor_messages.text is
  'Redacted text only. The raw text of a child never reaches the database (CLAUDE.md rule 3).';

-- tutor_daily_usage ---------------------------------------------------------------------------------------------------
create table public.tutor_daily_usage (
  child_id uuid not null,
  household_id uuid not null,
  -- the child's day in Africa/Lagos (the limit resets at local midnight)
  day date not null,
  turns int not null default 0 check (turns >= 0),
  -- the turn that was counted last: a retry of it (same client_turn_id) is not counted twice
  last_turn_id uuid,
  primary key (child_id, day),
  constraint tutor_daily_usage_child_household_fk foreign key (child_id, household_id)
    references public.children (id, household_id) on delete cascade
);
create index tutor_daily_usage_child_household_idx on public.tutor_daily_usage (child_id, household_id);
create index tutor_daily_usage_day_idx on public.tutor_daily_usage (day);

comment on table public.tutor_daily_usage is
  'The daily turn counter of the budget. Written only by tutor_reserve_turn / tutor_save_turn; no client privilege.';

-- safeguarding_cases --------------------------------------------------------------------------------------------------
create table public.safeguarding_cases (
  id uuid primary key default gen_random_uuid(),
  -- the case outlives the purge of its messages and session
  session_id uuid references public.tutor_sessions (id) on delete set null,
  -- the CHILD message of the flagged turn
  message_id uuid references public.tutor_messages (id) on delete set null,
  client_turn_id uuid not null,
  household_id uuid not null,
  child_id uuid not null,
  category text not null check (
    category in ('self_harm', 'abuse_disclosure', 'distress', 'sexual', 'violence', 'personal_info_shared', 'jailbreak', 'off_topic')
  ),
  severity text not null check (severity in ('low', 'medium', 'high')),
  status text not null default 'open' check (status in ('open', 'in_review', 'resolved')),
  -- the last messages of the session, REDACTED: [{role, text, at}]
  excerpt jsonb not null default '[]'::jsonb check (jsonb_typeof(excerpt) = 'array'),
  excerpt_cleared_at timestamptz,
  due_at timestamptz not null,
  assigned_to uuid references auth.users (id) on delete set null,
  decision text check (decision in ('release', 'keep_withheld', 'contact_guardian', 'escalated', 'no_action')),
  notes text check (notes is null or char_length(notes) <= 2000),
  created_at timestamptz not null default now(),
  in_review_at timestamptz,
  resolved_at timestamptz,
  -- set when the decision is `release`: the held turns become visible to the guardian
  released_at timestamptz,
  constraint safeguarding_cases_child_household_fk foreign key (child_id, household_id)
    references public.children (id, household_id) on delete cascade,
  -- resolved <=> a resolution time and a decision
  constraint safeguarding_cases_resolution_chk check (
    (status = 'resolved') = (resolved_at is not null) and (status = 'resolved') = (decision is not null)
  ),
  constraint safeguarding_cases_release_chk check (released_at is null or decision = 'release')
);
-- one case per turn: opening a case twice for the same message returns the first
create unique index safeguarding_cases_turn_uidx on public.safeguarding_cases (child_id, client_turn_id);
create index safeguarding_cases_child_household_idx on public.safeguarding_cases (child_id, household_id);
create index safeguarding_cases_child_created_idx on public.safeguarding_cases (child_id, created_at);
create index safeguarding_cases_queue_idx on public.safeguarding_cases (status, due_at);
create index safeguarding_cases_session_id_idx on public.safeguarding_cases (session_id);
create index safeguarding_cases_message_id_idx on public.safeguarding_cases (message_id);
create index safeguarding_cases_assigned_to_idx on public.safeguarding_cases (assigned_to);

comment on table public.safeguarding_cases is
  'The safeguarding review queue. Read and decided only through list/get/update_safeguarding_case (roles safeguarding and super_admin at aal2); every call writes an audit row. Redacted excerpts only.';

-- ai_usage: a tutor call belongs to a session, not to a job ---------------------------------------------------------------
alter table public.ai_usage add column tutor_session_id uuid references public.tutor_sessions (id) on delete set null;
create index ai_usage_tutor_session_id_idx on public.ai_usage (tutor_session_id);
alter table public.ai_usage add constraint ai_usage_one_owner_chk check (job_id is null or tutor_session_id is null);

comment on column public.ai_usage.tutor_session_id is
  'Set for the calls of a tutor turn (task tutor or moderation); job_id is null then. Tokens only, never text.';

-- RLS on, no policy, no privilege for any API role ----------------------------------------------------------------------------
alter table public.tutor_sessions enable row level security;
alter table public.tutor_messages enable row level security;
alter table public.tutor_daily_usage enable row level security;
alter table public.safeguarding_cases enable row level security;

revoke all on table
  public.tutor_sessions, public.tutor_messages, public.tutor_daily_usage, public.safeguarding_cases
  from public, anon, authenticated, service_role;
