#!/usr/bin/env node
// Generates supabase/seed/golden_unit2.sql: the demo/dev seed that gives the CUSTAR Tutor database one
// real, publishable unit (the golden fixture of packages/content-schema).
//
//   node scripts/generate-seed.mjs          write the file
//   node scripts/generate-seed.mjs --check  fail if the committed file is stale
//
// The fixtures are TypeScript, so they are bundled IN MEMORY with esbuild's JS API and imported from a data
// URL: nothing is written except the SQL. The SQL is idempotent (fixed UUIDs, ON CONFLICT DO NOTHING) and
// creates, as the table owner:
//   * the Basic Science P1 Term 1 scheme (status approved),
//   * Chapter 1 "Our World Around Us" with units 1-4 (weeks 1-4 of the NERDC scheme; a chapter needs 3-5
//     units to be published, units 1, 3 and 4 are drafts without a version),
//   * an APPROVED unit_versions row for Unit 2 whose content is `goldenUnit2`.
// It does NOT publish. Publishing is an admin action (private.publish_unit_version needs an admin at aal2):
// run `select public.publish_unit_version('<version id>')` as an admin, then `publish-pack` builds the pack.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { build } from 'esbuild';

const root = new URL('..', import.meta.url).pathname;
const entry = join(root, 'packages/content-schema/src/fixtures/index.ts');
const outFile = join(root, 'supabase/seed/golden_unit2.sql');
const check = process.argv.includes('--check');

// fixed ids, so that the seed can run twice and other tooling can refer to them
export const IDS = {
  scheme: '0b5c0001-0000-4000-8000-000000000001',
  chapter: '0b5c0002-0000-4000-8000-000000000001',
  unit: (n) => `0b5c0003-0000-4000-8000-00000000000${n}`,
  goldenVersion: '0b5c0004-0000-4000-8000-000000000002',
};

const bundle = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  target: 'es2022',
  logLevel: 'silent',
});
const code = bundle.outputFiles[0].text;
const { goldenUnit2, p1BasicScienceTerm1 } = await import(
  `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`
);

const sql = (text) => `'${String(text).replaceAll("'", "''")}'`;

/** A dollar-quoted literal whose tag does not occur in the text. */
function dollar(text) {
  let tag = 'json';
  while (text.includes(`$${tag}$`)) tag += 'x';
  return `$${tag}$${text}$${tag}$`;
}

const header = goldenUnit2.header;
if (header.subject_slug !== 'basic-science' || header.level_code !== 'P1' || header.term !== 1) {
  throw new Error('goldenUnit2 is expected to be Basic Science, P1, Term 1');
}
if (header.chapter.number !== 1 || header.unit_no !== 2) {
  throw new Error('goldenUnit2 is expected to be Chapter 1, Unit 2');
}

// Chapter 1 = the first four teaching weeks of the scheme (units 1-4)
const weeks = p1BasicScienceTerm1.weeks.filter((w) => w.kind === 'teaching').slice(0, 4);
if (weeks.length !== 4) throw new Error('expected four teaching weeks in P1 Basic Science Term 1');

const unitRows = weeks.map((w, i) => {
  const unitNo = i + 1;
  const golden = unitNo === header.unit_no;
  return {
    id: IDS.unit(unitNo),
    unit_no: unitNo,
    week_no: golden ? header.week_no : w.week_no,
    title: golden ? header.title : w.topic,
    objective: golden ? header.objective : w.subtopics.join('; '),
    stage: golden ? header.stage : 'absorb',
  };
});
if (unitRows[header.unit_no - 1].week_no !== 2) throw new Error('Unit 2 is expected in week 2');

const lines = [];
lines.push(
  '-- GENERATED by scripts/generate-seed.mjs from packages/content-schema fixtures. Do not edit.',
  '-- Dev/demo seed: Basic Science P1 Term 1, Chapter 1 "Our World Around Us", and an APPROVED version of',
  '-- Unit 2 (the golden unit). Idempotent. It does not publish: see the comment of the generator.',
  'begin;',
  '',
  'insert into public.schemes (id, subject_id, level_code, term, status, source_note)',
  `select ${sql(IDS.scheme)}, s.id, 'P1', 1, 'approved',`,
  `       'NERDC Primary 1 Basic Science scheme of work (docs/reference); demo seed'`,
  `  from public.subjects s where s.slug = 'basic-science'`,
  'on conflict do nothing;',
  '',
  'insert into public.chapters (id, scheme_id, number, title)',
  `select ${sql(IDS.chapter)}, sc.id, ${header.chapter.number}, ${sql(header.chapter.title)}`,
  `  from public.schemes sc join public.subjects s on s.id = sc.subject_id`,
  ` where s.slug = 'basic-science' and sc.level_code = 'P1' and sc.term = 1`,
  'on conflict do nothing;',
  '',
  'insert into public.units (id, chapter_id, unit_no, week_no, kind, title, objective, stage)',
  "select v.id::uuid, ch.id, v.unit_no, v.week_no, 'lesson', v.title, v.objective, v.stage",
  '  from (values',
  unitRows
    .map(
      (u) =>
        `    (${sql(u.id)}, ${u.unit_no}, ${u.week_no}, ${sql(u.title)}, ${sql(u.objective)}, ${sql(u.stage)})`,
    )
    .join(',\n'),
  '  ) as v (id, unit_no, week_no, title, objective, stage)',
  `  join public.chapters ch on ch.id = ${sql(IDS.chapter)}::uuid`,
  'on conflict do nothing;',
  '',
  '-- the golden unit as an approved version (a reviewer approval is simulated by the owner here)',
  'insert into public.unit_versions (id, unit_id, version, schema_version, content, status, generated_by)',
  `select ${sql(IDS.goldenVersion)}::uuid, u.id, 1, ${goldenUnit2.schema_version},`,
  `       ${dollar(JSON.stringify(goldenUnit2))}::jsonb,`,
  `       'approved', 'human'`,
  `  from public.units u where u.id = ${sql(IDS.unit(header.unit_no))}::uuid`,
  'on conflict do nothing;',
  '',
  'commit;',
  '',
);
const output = lines.join('\n');

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== output) {
    console.error('supabase/seed/golden_unit2.sql is stale. Run `node scripts/generate-seed.mjs`.');
    process.exit(1);
  }
  console.log('golden_unit2.sql is up to date');
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, output);
  console.log(`wrote ${outFile} (${output.length} bytes)`);
}
