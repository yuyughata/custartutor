#!/usr/bin/env node
// Edge functions can only bundle files inside supabase/functions, so the tutor (@custar/tutor-core) is vendored there
// as a single bundled ES module. @custar/authoring-core (the model port), @custar/content-schema and zod are
// INLINED, so the `tutor-chat` function needs no import map. (vendor/content-schema.js and vendor/authoring-core.js
// inline their own copies of zod, about 0.8 MB each. That is harmless: schemas are plain objects and the platform
// limit is 20 MB.)
// The entry is src/index.ts: the contract, redaction, the safety layer, grounding and prompts, the turn pipeline,
// the streaming Anthropic adapter, Tutor Lite and the SSE codec. The fakes (src/fakes) are not exported from it
// and are not bundled; neither is the offline test material.
//
//   node scripts/vendor-tutor.mjs          regenerate the vendored file
//   node scripts/vendor-tutor.mjs --check  fail if the committed file is stale (CI)
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { build } from 'esbuild';

const root = new URL('..', import.meta.url).pathname;
const entry = join(root, 'packages/tutor-core/src/index.ts');
const outFile = join(root, 'supabase/functions/_shared/vendor/tutor-core.js');
const check = process.argv.includes('--check');

if (!existsSync(entry)) {
  console.error(`tutor-core has no ${entry}; nothing to vendor.`);
  process.exit(1);
}

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'esm',
  // Neutral: no Node built-ins are resolved, so an accidental `node:` import fails the build instead of
  // failing later inside Deno.
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  legalComments: 'none',
  banner: {
    js: '// GENERATED by scripts/vendor-tutor.mjs from packages/tutor-core. Do not edit.',
  },
});

const next = result.outputFiles[0].text;

const forbidden = /\bfrom\s*["'](?:node:|npm:|@anthropic-ai\/)|\brequire\(|\bprocess\.env\b/.exec(next);
if (forbidden) {
  console.error(`The bundle is not platform neutral (found "${forbidden[0]}").`);
  process.exit(1);
}

const kb = (Buffer.byteLength(next) / 1024).toFixed(1);

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== next) {
    console.error(
      'Vendored tutor-core is stale. Run `node scripts/vendor-tutor.mjs` and commit the result.',
    );
    process.exit(1);
  }
  console.log(`vendored tutor-core is up to date (${kb} KB)`);
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, next);
  console.log(`wrote ${outFile} (${kb} KB)`);
}
