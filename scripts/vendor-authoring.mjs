#!/usr/bin/env node
// Edge functions can only bundle files inside supabase/functions, so the content engine
// (@custar/authoring-core) is vendored there as a single bundled ES module. @custar/content-schema and zod are
// INLINED, so the edge function needs no import map. (vendor/content-schema.js inlines zod as well, so a
// function that imports both carries two copies of zod, about 0.8 MB each. That is harmless: schemas are plain
// objects and the platform limit is 20 MB.)
// The entry is src/index.ts: the contract, the Anthropic adapter, the step engine and the job driver. The test
// doubles under src/fakes are not exported from it and are not bundled.
//
//   node scripts/vendor-authoring.mjs          regenerate the vendored file
//   node scripts/vendor-authoring.mjs --check  fail if the committed file is stale (CI)
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { build } from 'esbuild';

const root = new URL('..', import.meta.url).pathname;
const entry = join(root, 'packages/authoring-core/src/index.ts');
const outFile = join(root, 'supabase/functions/_shared/vendor/authoring-core.js');
const check = process.argv.includes('--check');

if (!existsSync(entry)) {
  console.error(`authoring-core has no ${entry}; nothing to vendor.`);
  process.exit(1);
}

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'esm',
  // Neutral: no Node built-ins are resolved, so an accidental `node:` import fails the build instead of
  // failing later inside Deno.
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  legalComments: 'none',
  banner: {
    js: '// GENERATED by scripts/vendor-authoring.mjs from packages/authoring-core. Do not edit.',
  },
});

const next = result.outputFiles[0].text;

const forbidden = /\bfrom\s*["'](?:node:|npm:|@anthropic-ai\/)|\brequire\(|\bprocess\.env\b/.exec(
  next,
);
if (forbidden) {
  console.error(`The bundle is not platform neutral (found "${forbidden[0]}").`);
  process.exit(1);
}

const kb = (Buffer.byteLength(next) / 1024).toFixed(1);

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== next) {
    console.error(
      'Vendored authoring-core is stale. Run `node scripts/vendor-authoring.mjs` and commit the result.',
    );
    process.exit(1);
  }
  console.log(`vendored authoring-core is up to date (${kb} KB)`);
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, next);
  console.log(`wrote ${outFile} (${kb} KB)`);
}
