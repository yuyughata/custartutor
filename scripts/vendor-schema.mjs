#!/usr/bin/env node
// Edge functions can only bundle files inside supabase/functions, so the shared
// content-schema package is vendored there as a single bundled ES module.
//
//   node scripts/vendor-schema.mjs          regenerate the vendored file
//   node scripts/vendor-schema.mjs --check  fail if the committed file is stale (CI)
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { build } from 'esbuild';

const root = new URL('..', import.meta.url).pathname;
const entry = join(root, 'packages/content-schema/src/index.ts');
const outFile = join(root, 'supabase/functions/_shared/vendor/content-schema.js');
const check = process.argv.includes('--check');

if (!existsSync(entry)) {
  console.log('content-schema has no src/index.ts yet; nothing to vendor.');
  process.exit(0);
}

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  legalComments: 'none',
  banner: {
    js: '// GENERATED by scripts/vendor-schema.mjs from packages/content-schema. Do not edit.',
  },
});

const next = result.outputFiles[0].text;

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== next) {
    console.error('Vendored content-schema is stale. Run `npm run vendor` and commit the result.');
    process.exit(1);
  }
  console.log('vendored content-schema is up to date');
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, next);
  console.log(`wrote ${outFile}`);
}
